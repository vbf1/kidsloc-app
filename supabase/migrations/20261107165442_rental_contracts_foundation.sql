create table if not exists public.rental_contracts (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  rental_id uuid not null references public.rentals(id) on delete cascade,
  contract_number bigint generated by default as identity,
  status text not null default 'draft'
    check (status in ('draft','sent','viewed','signed','cancelled','expired')),
  signature_method text not null
    check (signature_method in ('external','in_app')),
  contract_snapshot jsonb not null default '{}'::jsonb,
  token_hash text unique,
  token_expires_at timestamptz,
  sent_at timestamptz,
  viewed_at timestamptz,
  signed_at timestamptz,
  constraint rental_contracts_signed_fields_check check (status <> 'signed' or signed_at is not null),
  signer_name text,
  signer_document text,
  signer_phone text,
  signature_svg text,
  consent_text text,
  signer_ip inet,
  signer_user_agent text,
  original_pdf_path text,
  signed_pdf_path text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists rental_contracts_company_created_idx
  on public.rental_contracts(company_id, created_at desc);
create index if not exists rental_contracts_rental_idx
  on public.rental_contracts(rental_id);
create index if not exists rental_contracts_status_idx
  on public.rental_contracts(company_id, status);

alter table public.rental_contracts enable row level security;

