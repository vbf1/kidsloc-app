create table public.rental_quotes (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  customer_id uuid,
  quote_number bigint generated by default as identity,
  status text not null default 'draft'
    check (status in ('draft','sent','accepted','rejected','expired','converted','cancelled')),
  issue_date date not null default current_date,
  valid_until date,
  event_date date,
  start_time time,
  end_time time,
  delivery_method text not null default 'delivery'
    check (delivery_method in ('delivery','customer_pickup')),
  delivery_address text,
  delivery_fee numeric(12,2) not null default 0 check (delivery_fee >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  total_amount numeric(12,2) not null default 0 check (total_amount >= 0),
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, id),
  unique (company_id, quote_number),
  constraint rental_quotes_company_customer_fkey
    foreign key (company_id, customer_id)
    references public.customers(company_id, id) on delete set null (customer_id)
);

create table public.rental_quote_items (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null,
  quote_id uuid not null,
  product_id uuid not null,
  description text not null,
  quantity integer not null default 1 check (quantity > 0),
  unit_price numeric(12,2) not null default 0 check (unit_price >= 0),
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  created_at timestamptz not null default now(),
  constraint rental_quote_items_company_quote_fkey
    foreign key (company_id, quote_id)
    references public.rental_quotes(company_id, id) on delete cascade,
  constraint rental_quote_items_company_product_fkey
    foreign key (company_id, product_id)
    references public.products(company_id, id)
);

create index rental_quotes_company_issue_date_idx
  on public.rental_quotes(company_id, issue_date desc);
create index rental_quotes_company_status_idx
  on public.rental_quotes(company_id, status);
create index rental_quote_items_quote_idx
  on public.rental_quote_items(company_id, quote_id);

create trigger rental_quotes_set_updated_at
  before update on public.rental_quotes
  for each row execute function public.set_updated_at();

alter table public.rental_quotes enable row level security;
alter table public.rental_quote_items enable row level security;

create policy rental_quotes_select_company_members
  on public.rental_quotes for select to authenticated
  using (public.is_company_member(company_id));
create policy rental_quotes_insert_company_members
  on public.rental_quotes for insert to authenticated
  with check (public.is_company_member(company_id));
create policy rental_quotes_update_company_members
  on public.rental_quotes for update to authenticated
  using (public.is_company_member(company_id))
  with check (public.is_company_member(company_id));
create policy rental_quotes_delete_owner_admin
  on public.rental_quotes for delete to authenticated
  using (public.has_company_role(company_id, array['owner','admin']));

create policy rental_quote_items_select_company_members
  on public.rental_quote_items for select to authenticated
  using (public.is_company_member(company_id));
create policy rental_quote_items_insert_company_members
  on public.rental_quote_items for insert to authenticated
  with check (
    public.is_company_member(company_id)
    and exists (select 1 from public.rental_quotes q
      where q.id = quote_id and q.company_id = rental_quote_items.company_id)
  );
create policy rental_quote_items_update_company_members
  on public.rental_quote_items for update to authenticated
  using (public.is_company_member(company_id))
  with check (
    public.is_company_member(company_id)
    and exists (select 1 from public.rental_quotes q
      where q.id = quote_id and q.company_id = rental_quote_items.company_id)
  );
create policy rental_quote_items_delete_owner_admin
  on public.rental_quote_items for delete to authenticated
  using (public.has_company_role(company_id, array['owner','admin']));
